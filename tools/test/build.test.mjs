/**
 * Makes an empty temporary folder, deleted after the last test of this file.
 * @returns {string} Absolute path.
 */
function makeTempDir() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pop-'));
  tempDirs.push(dir);
  return dir;
}

/**
 * Copies the sources the build reads into a temporary repository root, so a test can change them.
 * @returns {string} The copy's root.
 */
function copySources() {
  const root = makeTempDir();
  for (const dir of SOURCE_DIRS) fs.cpSync(path.join(ROOT, dir), path.join(root, dir), { recursive: true });
  return root;
}

/**
 * Rewrites one file of a source copy.
 * @param {string} root - Root of the copy.
 * @param {string} file - Path relative to the root.
 * @param {(contents: string) => string} change - Returns the new contents.
 * @returns {void}
 */
function editSource(root, file, change) {
  const target = path.join(root, file);
  const original = fs.readFileSync(target, 'utf8');
  const changed = change(original);
  assert.notEqual(changed, original, `${file} was changed`);
  fs.writeFileSync(target, changed);
}

/**
 * Writes a file into a folder, creating its sub-folders.
 * @param {string} dir - Folder.
 * @param {string} file - Path relative to the folder ("/"-separated).
 * @param {string} contents - File contents.
 * @returns {void}
 */
function plant(dir, file, contents) {
  fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
  fs.writeFileSync(path.join(dir, file), contents);
}

/**
 * Lists every file under a folder.
 * @param {string} dir - Folder.
 * @returns {string[]} Paths relative to it, "/"-separated, sorted.
 */
function listFiles(dir) {
  return fs.readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(dir, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'))
    .sort();
}

/**
 * Reads a generated file.
 * @param {string} file - Path relative to the output folder.
 * @param {string} [dir=outDir] - Output folder (default: the main build's).
 * @returns {string} File contents.
 */
function read(file, dir = outDir) {
  return fs.readFileSync(path.join(dir, file), 'utf8');
}

/**
 * The generated site pages: every .html file but 404.html (a fixed noindex page without scripts, JSON-LD
 * or hero, tested on its own).
 * @returns {string[]} Paths relative to the output folder.
 */
function sitePages() {
  return result.files.filter((name) => name.endsWith('.html') && name !== '404.html');
}

/**
 * Parses the JSON-LD graph of a generated page.
 * @param {string} html - Page markup.
 * @returns {object[]} The @graph nodes.
 */
function graphOf(html) {
  const match = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
  assert.ok(match, 'page has a JSON-LD script');
  return JSON.parse(match[1])['@graph'];
}

/**
 * Pixel size of a WebP file, from its header (lossy VP8, lossless VP8L or extended VP8X).
 * @param {string} file - Absolute path.
 * @returns {{width: number, height: number}|null} Size, or null when the file is not a WebP.
 */
function webpSize(file) {
  const bytes = fs.readFileSync(file);
  if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') return null;
  const chunk = bytes.toString('ascii', 12, 16);
  if (chunk === 'VP8 ') return { width: bytes.readUInt16LE(26) & 0x3fff, height: bytes.readUInt16LE(28) & 0x3fff };
  if (chunk === 'VP8L') {
    const bits = bytes.readUInt32LE(21);
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
  }
  if (chunk === 'VP8X') return { width: bytes.readUIntLE(24, 3) + 1, height: bytes.readUIntLE(27, 3) + 1 };
  return null;
}

