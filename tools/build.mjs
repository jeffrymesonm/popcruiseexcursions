/** Template whose price tables are the single source of prices. */
const MAIN_TEMPLATE = 'src/index.html';
/** Template of the page GitHub Pages serves, with status 404, for any unknown URL (at any folder depth). */
const NOT_FOUND_TEMPLATE = 'src/404.html';
/** Where GitHub Pages looks for it. */
const NOT_FOUND_FILE = '404.html';
/** Folder of the {{include:…}} partials. */
const PARTIALS_DIR = 'src/partials';
/** Lengths above which search results cut the title / description (warnings, not errors). */
const TITLE_MAX = 65;
const DESCRIPTION_MAX = 165;
/** Start of the banner on line 2 of every file the build marks as generated (the proof it may delete it). */
const GENERATED_MARK = '<!-- GENERATED by tools/build.mjs';
/** Kinds of files that carry the banner: the only ones the stale-file cleanup looks at. */
const MARKED_EXTENSIONS = ['.html', '.xml'];
/**
 * Top-level folders the stale-file cleanup never enters (sources, tooling, internal notes), even if a copy
 * of a generated page sits there. node_modules and dot-folders are skipped at any depth.
 */
const UNCLEANED_DIRS = ['assets', 'docs', 'src', 'tools'];
/** Hex characters of the sha256 content hash written as ?v= on scripts and stylesheets. */
const VERSION_LENGTH = 8;
/** Bytes of a page within which its <meta charset> must end (browsers look for the encoding there). */
const CHARSET_WITHIN = 1024;
/** How llms.txt says what one "from" price buys, by pricing model (per-person prices need no unit). */
const PRICE_UNITS = { charter: 'per boat', vehicle: 'per vehicle' };

/**
 * Output file of a URL path.
 * @param {string} urlPath - "/" or "/es/excursiones-amber-cove/".
 * @returns {string} "index.html" or "es/excursiones-amber-cove/index.html".
 */
function outputFile(urlPath) {
  return `${urlPath.slice(1)}index.html`;
}

/**
 * The home page definition.
 * @returns {object} PageDef with id "home".
 */
function homePage() {
  return config.PAGES.find((page) => page.id === 'home');
}

/**
 * URL path of the home page in a language (the default language when it has no such version).
 * @param {string} lang - Language code.
 * @returns {string} URL path.
 */
function homePath(lang) {
  const home = homePage();
  return home.versions[lang] || home.versions[config.DEFAULT_LANG];
}

/**
 * Page definition by id.
 * @param {string} pageId - "home", "amber-cove", "catamaran"…
 * @returns {object|undefined} PageDef, or undefined when there is no such page.
 */
function pageById(pageId) {
  return config.PAGES.find((page) => page.id === pageId);
}

/**
 * Absolute URL of a tour: its own landing page in that language when there is one (the catamaran
 * page), else its card on the home page.
 * @param {string} tourId - TOURS id.
 * @param {string} lang - Language code.
 * @returns {string} Absolute URL.
 */
function tourUrl(tourId, lang) {
  const landing = config.PAGES.find((page) => page.tour === tourId && page.versions[lang]);
  if (landing) return absoluteUrl(config.SITE.origin, landing.versions[lang]);
  return `${absoluteUrl(config.SITE.origin, homePath(lang))}#tour-${tourId}`;
}

/**
 * Replaces the {{price-tables}} marker of a template with hidden copies of the per-person and vehicle price tables
 * of the main template, before translation (so they are translated like the rest of the page). Pages
 * with the booking form but without the tour cards (the catamaran page) use it so the form can price
 * every tour; prices still live only in src/index.html.
 * @param {string} template - Page template, after includes.
 * @param {string} mainTemplate - src/index.html, after includes.
 * @returns {string} Template with the marker replaced (unchanged when it has no marker).
 */
function withPriceTables(template, mainTemplate) {
  if (!template.includes('{{price-tables}}')) return template;
  const block = [
    '    <!-- Per-person and vehicle price tables copied by tools/build.mjs from src/index.html (hidden): the booking form prices every tour with them. -->',
    '    <div hidden data-price-tables>',
    ...formTablesHtml(mainTemplate),
    '    </div>'
  ].join('\n');
  return template.replace(/[ \t]*\{\{price-tables\}\}/, block);
}

/**
 * Price range of the business: lowest per-person price to the highest price of any table.
 * @param {Array<object>} tables - Parsed price tables.
 * @returns {string} E.g. "US$12–US$1,300" ('' when there are no prices).
 */
function priceRange(tables) {
  const low = minPrice(tables, 'all');
  const highs = tables.map((table) => maxPrice(tables, table.id)).filter((amount) => amount !== null);
  return low === null || !highs.length ? '' : `${formatUsd(low)}–${formatUsd(Math.max(...highs))}`;
}

/**
 * Reads a dictionary entry, recording an error when it is missing.
 * @param {Record<string, string>} dict - Dictionary of the page language.
 * @param {string} key - Translation key.
 * @param {string[]} errors - Collects build errors.
 * @param {string} where - Page label for the error message.
 * @returns {string} The text ('' when missing).
 */
function textOf(dict, key, errors, where) {
  if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
  errors.push(`${where}: missing text for "${key}"`);
  return '';
}

/**
 * FAQ keys of a template, in document order: "faq.1", "port.ac.faq.2"… (each has .q and .a).
 * @param {string} html - Template.
 * @returns {string[]} Key prefixes.
 */
function faqKeys(html) {
  const keys = [];
  for (const match of html.matchAll(/\sdata-i18n="((?:[\w-]+\.)*faq\.\d+)\.q"/g)) {
    if (!keys.includes(match[1])) keys.push(match[1]);
  }
  return keys;
}

/**
 * Questions and answers of a page in one language.
 * @param {string} template - Template.
 * @param {Record<string, string>} dict - Dictionary of the page language.
 * @param {string[]} errors - Collects build errors.
 * @param {string} where - Page label.
 * @returns {Array<{q: string, a: string}>} FAQ entries.
 */
function faqOf(template, dict, errors, where) {
  return faqKeys(template).map((key) => ({
    q: textOf(dict, `${key}.q`, errors, where),
    a: textOf(dict, `${key}.a`, errors, where)
  }));
}

/**
 * Title and description of a rendered page.
 * @param {string} html - Page markup.
 * @returns {{title: string, description: string}} Decoded texts ('' when absent).
 */
function pageMeta(html) {
  const title = (html.match(/<title\b[^>]*>([^<]*)<\/title>/) || [null, ''])[1];
  const description = (html.match(/<meta name="description" content="([^"]*)"/) || [null, ''])[1];
  return { title: decodeEntities(title), description: decodeEntities(description) };
}

/**
 * The six tours in one language, for the JSON-LD and llms.txt.
 * @param {Record<string, string>} dict - Dictionary of the language.
 * @param {string} lang - Language code (decides which home page the tour links point to).
 * @param {Array<object>} tables - Parsed price tables.
 * @param {string[]} errors - Collects build errors.
 * @param {string} where - Page label.
 * @returns {Array<object>} TourData list (see tools/lib/schema.mjs).
 */
function toursOf(dict, lang, tables, errors, where) {
  return config.TOURS.map((tour) => {
    const low = tour.scope ? minPrice(tables, tour.scope) : null;
    return {
      id: tour.id,
      name: textOf(dict, `tours.${tour.id}.title`, errors, where),
      description: textOf(dict, `tours.${tour.id}.desc`, errors, where),
      image: tour.image,
      url: tourUrl(tour.id, lang),
      offer: low === null ? null : { low, high: maxPrice(tables, tour.scope), count: priceCount(tables, tour.scope) },
      stops: tour.stops
        ? Array.from({ length: tour.stops }, (unused, index) => textOf(dict, `tours.${tour.id}.stop${index + 1}`, errors, where))
        : undefined
    };
  });
}

/**
 * Data of the port a page is about, for its JSON-LD.
 * @param {object} page - PageDef with a port.
 * @param {Record<string, string>} dict - Dictionary of the language.
 * @param {string[]} errors - Collects build errors.
 * @param {string} where - Page label.
 * @returns {object|undefined} PortData (see tools/lib/schema.mjs), or undefined for non-port pages.
 */
function portOf(page, dict, errors, where) {
  if (!page.port) return undefined;
  const port = config.PORTS[page.port];
  if (!port) {
    errors.push(`${where}: tools/site.config.mjs has no PORTS entry for "${page.port}"`);
    return undefined;
  }
  return {
    id: page.port,
    name: port.name,
    geo: port.geo,
    homeName: textOf(dict, 'port.home', errors, where),
    pageName: textOf(dict, `port.${port.key}.h1`, errors, where)
  };
}

/**
 * Kind of page, for its JSON-LD.
 * @param {object} page - PageDef.
 * @returns {'home'|'port'|'tour'|'legal'} "port" for cruise-port pages, "tour" for one-tour pages, "legal"
 *   for the privacy policy and the booking terms, else "home".
 */
function pageTypeOf(page) {
  if (page.port) return 'port';
  if (page.tour) return 'tour';
  return page.legal ? 'legal' : 'home';
}

/**
 * Breadcrumb names of a legal page (privacy policy, booking terms), for its JSON-LD.
 * @param {object} page - PageDef with legal and a textKey (its H1 is "<textKey>.h1").
 * @param {Record<string, string>} dict - Dictionary of the language.
 * @param {string[]} errors - Collects build errors.
 * @param {string} where - Page label.
 * @returns {{homeName: string, pageName: string}|undefined} LegalPageData (see tools/lib/schema.mjs), or
 *   undefined for other pages.
 */
function legalPageOf(page, dict, errors, where) {
  if (!page.legal) return undefined;
  return {
    homeName: textOf(dict, 'port.home', errors, where),
    pageName: textOf(dict, `${page.textKey}.h1`, errors, where)
  };
}

/**
 * Data of the tour a tour page is about (e.g. the catamaran page), for its JSON-LD.
 * @param {object} page - PageDef with a tour and a textKey (its H1 is "<textKey>.h1").
 * @param {Record<string, string>} dict - Dictionary of the language.
 * @param {string[]} errors - Collects build errors.
 * @param {string} where - Page label.
 * @returns {object|undefined} TourPageData (see tools/lib/schema.mjs), or undefined for other pages.
 */
function tourPageOf(page, dict, errors, where) {
  if (!page.tour) return undefined;
  if (!config.TOURS.some((tour) => tour.id === page.tour)) {
    errors.push(`${where}: tools/site.config.mjs has no TOURS entry for "${page.tour}"`);
    return undefined;
  }
  return {
    id: page.tour,
    homeName: textOf(dict, 'port.home', errors, where),
    pageName: textOf(dict, `${page.textKey}.h1`, errors, where)
  };
}

/**
 * Value of a template marker for one page version.
 * @param {{page: object, lang: string, urlPath: string, seoHead: string, readPartial: Function,
 *   hasBooking: boolean}} context - hasBooking: the page has the booking form (id="booking").
 * @returns {(name: string, arg: string|null) => string|undefined} Resolver for fillPlaceholders.
 */
function markerResolver({ page, lang, urlPath, seoHead, readPartial, hasBooking }) {
  return (name, arg) => {
    if (name === 'home' && arg === null) return relativeUrl(urlPath, homePath(lang));
    // {{root}}: the path back to the site root ('' on "/", "../" on "/es/"), for files that live there
    // (favicon.ico: crawlers and browsers also request /favicon.ico without a link).
    if (name === 'root' && arg === null) return rootPrefix(urlPath);
    // {{book-url}}: the booking form of this page when it has one (home, catamaran page), else the home page's.
    if (name === 'book-url' && arg === null) return hasBooking ? '#booking' : `${relativeUrl(urlPath, homePath(lang))}#booking`;
    if (name === 'current' && arg) return arg === lang ? ' aria-current="page"' : '';
    if (name === 'seo-head' && arg === null) return seoHead;
    if (name === 'root-redirect' && arg === null) return urlPath === '/' ? readPartial('root-redirect.html') : '';
    if (name === 'lang-url' && arg) {
      // This page in that language; without that version, that language's home page (at the tour's
      // card for a tour page, so French visitors of the catamaran page land on the French boats card).
      let target = page.versions[arg];
      let hash = '';
      if (!target) {
        target = homePage().versions[arg];
        if (page.tour) hash = `#tour-${page.tour}`;
      }
      if (!target) return undefined;
      // "/" redirects by saved choice or browser language: the explicit ?lang keeps the visitor's pick
      // even when localStorage is blocked or the click happens before i18n.js has loaded.
      const query = target === '/' ? `?lang=${arg}` : '';
      return `${relativeUrl(urlPath, target) || './'}${query}${hash}`;
    }
    // {{page-url:<page id>}} / {{page-lang:<page id>}}: link to another page in this language. When that
    // page has no version in it, a tour page falls back to its card on this language's home page (FR/IT
    // → the translated boats card) and any other page to its default-language version (FR/IT → the
    // English port pages, which have no translated equivalent).
    if ((name === 'page-url' || name === 'page-lang') && arg) {
      const target = pageById(arg);
      if (!target) return undefined;
      if (!target.versions[lang] && target.tour && homePage().versions[lang]) {
        return name === 'page-lang' ? lang : `${relativeUrl(urlPath, homePath(lang))}#tour-${target.tour}`;
      }
      const targetLang = target.versions[lang] ? lang : config.DEFAULT_LANG;
      return name === 'page-lang' ? targetLang : relativeUrl(urlPath, target.versions[targetLang]) || './';
    }
    return undefined;
  };
}

/**
 * Adds the GENERATED banner as line 2, right after the line the format needs first (the doctype of a
 * page, the XML declaration of sitemap.xml). It is an HTML/XML comment without "--", so both stay valid.
 * @param {string} contents - File contents.
 * @param {string} source - What the file is generated from, e.g. "src/index.html (en)".
 * @param {string} change - What to edit instead, e.g. "src/ or the dictionaries".
 * @returns {string} Contents with the banner on line 2.
 */
function addBanner(contents, source, change) {
  const banner = `${GENERATED_MARK} from ${source}. Do not edit: change ${change} and run "node tools/build.mjs". -->`;
  return contents.replace(/^[^\n]*\n/, (firstLine) => `${firstLine}${banner}\n`);
}

/**
 * Tells whether a file was written by this build: its line 2 is the GENERATED banner.
 * @param {string} contents - File contents.
 * @returns {boolean} True for generated pages and sitemap.xml.
 */
function isGenerated(contents) {
  const secondLine = contents.split('\n', 2)[1];
  return secondLine !== undefined && secondLine.startsWith(GENERATED_MARK);
}

/**
 * Lists the files of a folder that may carry the GENERATED banner (.html and .xml), skipping the
 * folders the build must never clean.
 * @param {string} outDir - Output folder.
 * @param {string} [relativeDir=''] - Sub-folder being listed ("/"-separated, '' for outDir itself).
 * @returns {string[]} Paths relative to outDir, "/"-separated.
 */
function markableFiles(outDir, relativeDir = '') {
  const entries = fs.readdirSync(path.join(outDir, relativeDir), { withFileTypes: true });
  return entries.flatMap((entry) => {
    const relative = relativeDir ? `${relativeDir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      const skipped = entry.name.startsWith('.') || entry.name === 'node_modules'
        || (!relativeDir && UNCLEANED_DIRS.includes(entry.name.toLowerCase()));
      return skipped ? [] : markableFiles(outDir, relative);
    }
    return entry.isFile() && MARKED_EXTENSIONS.includes(path.extname(entry.name).toLowerCase()) ? [relative] : [];
  });
}

/**
 * Deletes the files an earlier build generated that this build no longer writes (a renamed or removed
 * page), and the folders that become empty. Only files whose line 2 is the GENERATED banner are touched.
 * @param {string} outDir - Output folder.
 * @param {Set<string>} written - Files this build wrote (relative to outDir, "/"-separated).
 * @returns {string[]} Deleted files, relative to outDir.
 */
function removeStaleFiles(outDir, written) {
  const stale = markableFiles(outDir)
    .filter((file) => !written.has(file) && isGenerated(fs.readFileSync(path.join(outDir, file), 'utf8')));
  for (const file of stale) {
    fs.rmSync(path.join(outDir, file));
    // Remove the folders the page leaves empty, from the deepest up to (not including) outDir.
    for (let dir = path.posix.dirname(file); dir !== '.'; dir = path.posix.dirname(dir)) {
      const folder = path.join(outDir, dir);
      if (fs.readdirSync(folder).length) break;
      fs.rmdirSync(folder);
    }
  }
  return stale;
}

/**
 * Version of a local script or stylesheet for its ?v= query: the start of the sha256 of its text with every
 * CRLF line break read as LF, so it changes exactly when the file does and is the same in every checkout.
 * (With core.autocrlf=true a Windows working tree holds some files with CRLF and others with LF, while git
 * stores and GitHub Pages serves LF: hashing the raw bytes gave each checkout its own versions.)
 * @param {string} root - Repository root.
 * @param {string} assetPath - Site-relative path, e.g. "assets/js/i18n.js".
 * @returns {string|null} VERSION_LENGTH hex characters, or null when the file does not exist.
 */
export function assetVersion(root, assetPath) {
  try {
    const text = fs.readFileSync(path.join(root, assetPath), 'utf8').replace(/\r\n/g, '\n');
    return createHash('sha256').update(text).digest('hex').slice(0, VERSION_LENGTH);
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

/**
 * Final checks on a rendered page.
 * @param {string} html - Page markup.
 * @param {string} where - Page label.
 * @param {string[]} errors - Collects build errors.
 * @param {string[]} warnings - Collects warnings.
 * @returns {void}
 */
function validatePage(html, where, errors, warnings) {
  if (!/^<!doctype html>\r?\n<!-- GENERATED/i.test(html)) errors.push(`${where}: missing doctype or GENERATED banner`);
  const charset = html.match(/<meta charset="[^"]*">/i);
  const charsetEnd = charset ? Buffer.byteLength(html.slice(0, charset.index + charset[0].length)) : null;
  if (charsetEnd === null || charsetEnd > CHARSET_WITHIN) {
    errors.push(`${where}: <meta charset> must end within the first ${CHARSET_WITHIN} bytes (${charset ? `ends at byte ${charsetEnd}` : 'missing'})`);
  }
  const leftover = html.match(/\{\{[^}]*\}\}/);
  if (leftover) errors.push(`${where}: unresolved marker ${leftover[0]}`);
  const headings = (html.match(/<h1[\s>]/g) || []).length;
  if (headings !== 1) errors.push(`${where}: ${headings} <h1> elements (expected 1)`);
  const { title, description } = pageMeta(html);
  if (title.length > TITLE_MAX) warnings.push(`${where}: <title> has ${title.length} characters (search shows ~${TITLE_MAX})`);
  if (description.length > DESCRIPTION_MAX) {
    warnings.push(`${where}: description has ${description.length} characters (search shows ~${DESCRIPTION_MAX})`);
  }
}

/**
 * Renders one language version of a page.
 * @param {object} input - { page, lang, urlPath, template, data, tables, site, readPartial, versionOf,
 *   dictionaries, errors, warnings, where } (versionOf: ?v= version of a local script or stylesheet).
 * @returns {string} Final page markup.
 */
function renderVersion({
  page, lang, urlPath, template, data, tables, site, readPartial, versionOf, dictionaries, errors, warnings, where
}) {
  if (lang !== 'es' && !dictionaries[lang]) errors.push(`${where}: no dictionary for "${lang}"`);
  const translated = translateHtml(template, lang === 'es' ? null : dictionaries[lang] || {});
  if (translated.missing.length) errors.push(`${where}: missing translations: ${translated.missing.join(', ')}`);
  if (translated.unprocessed.length) {
    errors.push(`${where}: data-i18n elements must hold plain text: ${translated.unprocessed.join(', ')}`);
  }
  let html = translated.html.replace(/<html lang="[a-z-]+"/i, `<html lang="${lang}"`);

  const { title, description } = pageMeta(html);
  const graph = buildGraph({
    origin: site.origin,
    site,
    lang,
    url: absoluteUrl(site.origin, urlPath),
    homeUrl: absoluteUrl(site.origin, homePath(lang)),
    pageType: pageTypeOf(page),
    title,
    description,
    audience: config.AUDIENCE[lang] || config.AUDIENCE[config.DEFAULT_LANG],
    tours: toursOf(data, lang, tables, errors, where),
    faq: faqOf(template, data, errors, where),
    port: portOf(page, data, errors, where),
    tourPage: tourPageOf(page, data, errors, where),
    legalPage: legalPageOf(page, data, errors, where)
  });
  const seoHead = `${seoHeadTags({ origin: site.origin, page, lang, locales: config.LOCALES, defaultLang: config.DEFAULT_LANG })}\n  ${jsonLdScript(graph)}`;

  const hasBooking = /\sid="booking"/.test(template);
  const filled = fillPlaceholders(html, markerResolver({ page, lang, urlPath, seoHead, readPartial, hasBooking }));
  if (filled.unknown.length) errors.push(`${where}: unknown markers: ${filled.unknown.join(', ')}`);
  const versioned = versionAssetUrls(selectLangScripts(stripTemplateOnly(filled.html), lang), versionOf);
  if (versioned.missing.length) errors.push(`${where}: scripts or stylesheets not found: ${versioned.missing.join(', ')}`);
  html = prefixAssetPaths(versioned.html, rootPrefix(urlPath));

  const priced = fillPriceFrom(html, tables);
  if (priced.unknown.length) errors.push(`${where}: "from" labels without a price table: ${priced.unknown.join(', ')}`);
  // The template comments are notes for whoever edits src/; the banner is added after they are stripped.
  html = addBanner(stripComments(priced.html), `${page.template} (${lang})`, 'src/ or the dictionaries');
  validatePage(html, where, errors, warnings);
  return html;
}

/**
 * The 404 page: its template as it is (one fixed page in four languages, so no translation and no
 * markers), without comments, with the GENERATED banner and the checks of every page. GitHub Pages serves
 * it from whatever folder the unknown URL names, so every src/href and CSS url() must be root-absolute
 * ("/…") or external (https:, mailto:).
 * @param {string} template - Contents of src/404.html.
 * @param {string[]} errors - Collects build errors.
 * @param {string[]} warnings - Collects warnings.
 * @returns {string} Page markup.
 */
function renderNotFound(template, errors, warnings) {
  const html = addBanner(stripComments(template), NOT_FOUND_TEMPLATE, 'that template');
  validatePage(html, NOT_FOUND_FILE, errors, warnings);
  const urls = [...html.matchAll(/\s(?:src|href|poster)="([^"]*)"|url\(["']?([^"')]*)["']?\)/g)]
    .map((match) => (match[1] === undefined ? match[2] : match[1]));
  const relative = urls.filter((url) => !/^(?:\/(?!\/)|https:\/\/|mailto:)/.test(url));
  if (relative.length) {
    errors.push(`${NOT_FOUND_FILE}: URLs must be root-absolute (the page is served at any depth): ${relative.join(', ')}`);
  }
  return html;
}

/**
 * Price lines of a vehicle table for llms.txt, one per vehicle ("Single ATV (1 person): US$90 per vehicle
 * for 1 to 2 vehicles, US$75 per vehicle for 3 or more vehicles"), plus the share that books it.
 * @param {object} table - Parsed table with pricing "vehicle" (see tools/lib/prices.mjs).
 * @param {Record<string, string>} dict - English dictionary (vehicle names).
 * @returns {string[]} The lines.
 */
function vehiclePriceLines(table, dict) {
  const ranges = table.columns.map(({ min, max }) => (max === null ? `${min} or more vehicles` : `${min} to ${max} vehicles`));
  const lines = table.rows.filter((row) => row.option && row.seats).map((row) => {
    const name = dict[row.nameKey] || row.option;
    const prices = row.cells
      .map((cell, index) => (cell === null || !ranges[index] ? null : `${formatUsd(cell)} per vehicle for ${ranges[index]}`))
      .filter(Boolean);
    return `${name} (${row.seats} ${row.seats === 1 ? 'person' : 'people'}): ${prices.join(', ')}`;
  });
  if (table.depositPercent) lines.push(`${table.depositPercent}% of the total to book`);
  return lines;
}

/**
 * Price lines of a tour for llms.txt ("1 to 5 people: US$100 with zipline, US$75 no zipline"); the
 * boats add one line per boat and one per tier of the optional round-trip transport, buggies one per
 * vehicle.
 * @param {string|null} scope - Price table id or data-tour group.
 * @param {Array<object>} tables - Parsed price tables.
 * @param {Record<string, string>} dict - English dictionary (column labels).
 * @param {Record<string, string>} boatNames - Boat id → English name.
 * @returns {string[]} One line per group size, or per boat for charters.
 */
function priceLines(scope, tables, dict, boatNames) {
  if (!scope) return [];
  return tables.filter((table) => table.id === scope || table.tour === scope).flatMap((table) => {
    if (table.pricing === 'transfer') {
      return table.rows
        .filter((row) => row.min !== null && row.max !== null && row.cells[0] !== null)
        .map((row) => `Optional round-trip transport port ↔ Sosúa, ${row.min} to ${row.max} people: ${formatUsd(row.cells[0])} for the group`);
    }
    if (table.pricing === 'vehicle') return vehiclePriceLines(table, dict);
    if (table.pricing === 'charter') {
      const flat = table.rows.find((row) => row.charge === 'flat');
      const extra = table.rows.find((row) => row.charge === 'extra');
      if (!flat || flat.cells[0] === null) return [];
      const name = boatNames[table.id.replace(/^boat-/, '')] || table.id;
      let line = `${name}: ${formatUsd(flat.cells[0])} for the whole boat (up to ${flat.max} people)`;
      if (extra && extra.cells[0] !== null) line += `, +${formatUsd(extra.cells[0])} per extra person`;
      if (table.deposit) line += `; ${formatUsd(table.deposit)} deposit to book`;
      return [line];
    }
    const lines = table.rows.filter((row) => row.min !== null && row.max !== null).map((row) => {
      const prices = row.cells
        .map((cell, index) => (cell === null ? null : `${formatUsd(cell)} ${(dict[table.optionKeys[index]] || table.options[index]).toLowerCase()}`))
        .filter(Boolean);
      return `${row.min} to ${row.max} people: ${prices.join(', ')}`;
    });
    if (table.depositPercent) lines.push(`${table.depositPercent}% of the total to book`);
    return lines;
  });
}

/**
 * Boat names of the booking form's boat picker, as written on a rendered page.
 * @param {string} html - Rendered page (English).
 * @returns {Record<string, string>} Boat id → name.
 */
function boatNamesOf(html) {
  const select = (html.match(/<select\b[^>]*\bid="booking-boat"[^>]*>([\s\S]*?)<\/select>/) || [null, ''])[1];
  const names = {};
  for (const match of select.matchAll(/<option value="([^"]+)"[^>]*>([^<]*)<\/option>/g)) {
    names[match[1]] = decodeEntities(match[2]).trim();
  }
  return names;
}

/**
 * llms.txt from the English pages.
 * @param {object} input - { site, dictEn, tables, mainTemplate, templates, rendered, errors }
 * @returns {string} Markdown document.
 */
function buildLlms({ site, dictEn, tables, mainTemplate, templates, rendered, errors }) {
  const where = 'llms.txt';
  const home = rendered.get(`home:${config.DEFAULT_LANG}`);
  const boatNames = boatNamesOf(home ? home.html : '');
  const tours = toursOf(dictEn, config.DEFAULT_LANG, tables, errors, where).map((tour) => {
    const definition = config.TOURS.find((item) => item.id === tour.id);
    // "US$75 per vehicle" / "US$900 per boat": what the lowest price buys, from the tour's pricing model.
    const unit = tour.offer ? PRICE_UNITS[scopePricing(tables, definition.scope)] : undefined;
    return {
      name: tour.name,
      url: tour.url,
      description: tour.description,
      from: tour.offer ? `${formatUsd(tour.offer.low)}${unit ? ` ${unit}` : ''}` : null,
      priceLines: priceLines(definition.scope, tables, dictEn, boatNames)
    };
  });
  // Links to the English version of one kind of page (port pages, legal pages), with its rendered title.
  const englishLinks = (isKind) => config.PAGES.filter((page) => isKind(page) && page.versions[config.DEFAULT_LANG])
    .map((page) => ({
      title: (rendered.get(`${page.id}:${config.DEFAULT_LANG}`) || { title: page.id }).title,
      url: absoluteUrl(site.origin, page.versions[config.DEFAULT_LANG])
    }));
  const ports = englishLinks((page) => page.port);
  const policies = englishLinks((page) => page.legal);
  const languages = config.PAGES.flatMap((page) => Object.entries(page.versions)
    .filter(([lang]) => lang !== config.DEFAULT_LANG)
    .map(([lang, urlPath]) => ({
      title: `${config.LANGUAGE_NAMES[lang]}: ${(rendered.get(`${page.id}:${lang}`) || { title: page.id }).title}`,
      url: absoluteUrl(site.origin, urlPath)
    })));
  const faq = [];
  for (const page of config.PAGES.filter((item) => item.versions[config.DEFAULT_LANG])) {
    for (const entry of faqOf(templates.get(page.id) || mainTemplate, dictEn, errors, where)) {
      if (!faq.some((known) => known.q === entry.q)) faq.push(entry);
    }
  }
  const summary = dictEn['about.lead'] || dictEn['meta.description'] || '';
  return llmsTxt({ site, summary, tours, ports, policies, languages, faq });
}

/**
 * Builds every page version, 404.html, sitemap.xml and llms.txt, then deletes the pages an earlier build
 * generated that are no longer built.
 * @param {{root: string, outDir?: string}} options - root: repository root; outDir: where to write (default root).
 * @returns {Promise<{files: string[], removed: string[], warnings: string[], errors: string[]}>} Written and
 *   deleted files (relative to outDir, "/"-separated), warnings, and errors (when there are errors nothing
 *   is written or deleted).
 */
export async function build({ root, outDir = root }) {
  const errors = [];
  const warnings = [];
  const outputs = new Map();
  const readSource = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
  const versions = new Map();
  const versionOf = (assetPath) => {
    if (!versions.has(assetPath)) versions.set(assetPath, assetVersion(root, assetPath));
    return versions.get(assetPath);
  };
  const readPartial = (name) => {
    try {
      return readSource(path.posix.join(PARTIALS_DIR, name)).replace(/\r?\n$/, '');
    } catch (error) {
      throw new Error(`partial "${name}" not found in ${PARTIALS_DIR}`);
    }
  };

  let dictionaries;
  let mainTemplate;
  try {
    dictionaries = loadDictionaries(config.DICTIONARY_FILES.map((file) => path.join(root, file)));
    mainTemplate = applyIncludes(readSource(MAIN_TEMPLATE), readPartial);
  } catch (error) {
    return { files: [], removed: [], warnings, errors: [error.message] };
  }
  const tables = parsePriceTables(mainTemplate);
  const mainBase = extractBaseDictionary(mainTemplate).dict;
  const site = { ...config.SITE, priceRange: priceRange(tables), languages: Object.keys(homePage().versions) };
  const rendered = new Map();
  const templates = new Map();

  for (const page of config.PAGES) {
    let template;
    try {
      template = page.template === MAIN_TEMPLATE
        ? mainTemplate
        : withPriceTables(applyIncludes(readSource(page.template), readPartial), mainTemplate);
    } catch (error) {
      errors.push(`${page.template}: ${error.message}`);
      continue;
    }
    templates.set(page.id, template);
    const base = extractBaseDictionary(template);
    if (base.conflicts.length) {
      errors.push(`${page.template}: same key with different Spanish texts: ${base.conflicts.join(', ')}`);
    }
    for (const [lang, urlPath] of Object.entries(page.versions)) {
      const where = `${outputFile(urlPath)} (${lang})`;
      const data = lang === 'es' ? { ...mainBase, ...base.dict } : dictionaries[lang] || {};
      try {
        const html = renderVersion({
          page, lang, urlPath, template, data, tables, site, readPartial, versionOf, dictionaries, errors, warnings, where
        });
        rendered.set(`${page.id}:${lang}`, { html, title: pageMeta(html).title });
        outputs.set(outputFile(urlPath), html);
      } catch (error) {
        errors.push(`${where}: ${error.message}`);
      }
    }
  }

  try {
    outputs.set(NOT_FOUND_FILE, renderNotFound(readSource(NOT_FOUND_TEMPLATE), errors, warnings));
  } catch (error) {
    errors.push(`${NOT_FOUND_TEMPLATE}: ${error.message}`);
  }

  const sitemap = sitemapXml({ origin: site.origin, pages: config.PAGES, defaultLang: config.DEFAULT_LANG });
  outputs.set('sitemap.xml', addBanner(sitemap, 'tools/site.config.mjs (PAGES)', 'its PAGES'));
  // llms.txt carries no banner: llmstxt.org wants its H1 first, and assistants read it verbatim.
  outputs.set('llms.txt', buildLlms({
    site, dictEn: dictionaries[config.DEFAULT_LANG] || {}, tables, mainTemplate, templates, rendered, errors
  }));

  if (errors.length) return { files: [], removed: [], warnings, errors };
  for (const [file, contents] of outputs) {
    const target = path.join(outDir, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, contents);
  }
  const removed = removeStaleFiles(outDir, new Set(outputs.keys()));
  return { files: [...outputs.keys()], removed, warnings, errors };
}

/**
 * Command-line entry: builds into the repository root, prints warnings and errors, and sets exit
 * code 1 when the build fails.
 * @returns {Promise<void>}
 */
async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const { files, removed, warnings, errors } = await build({ root });
  for (const warning of warnings) console.warn(`warning: ${warning}`);
  for (const error of errors) console.error(`error: ${error}`);
  if (errors.length) {
    console.error(`Build failed with ${errors.length} error(s); nothing was written.`);
    process.exitCode = 1;
    return;
  }
  console.log(`Built ${files.length} files: ${files.join(', ')}`);
  if (removed.length) console.log(`Removed ${removed.length} stale generated file(s): ${removed.join(', ')}`);
}

const invokedDirectly = Boolean(process.argv[1])
  && path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();
if (invokedDirectly) main();
